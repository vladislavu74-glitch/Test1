import Foundation

/// Статический справочник «страна → города» для вкладки «Критерии» — без
/// внешнего гео-API, просто заранее собранный список стран и крупных
/// городов СНГ, по которым и так уже работают источники (hh.ru покрывает
/// именно эти страны). Пользователь всё равно может добавить свою страну
/// или город вручную, если их нет в списке.
enum GeographyDirectory {
    static let countries: [String] = [
        "Россия", "Казахстан", "Беларусь", "Узбекистан", "Киргизия",
    ]

    static let citiesByCountry: [String: [String]] = [
        "Россия": [
            "Москва", "Санкт-Петербург", "Новосибирск", "Екатеринбург",
            "Казань", "Нижний Новгород", "Краснодар", "Самара",
            "Ростов-на-Дону", "Уфа", "Красноярск", "Воронеж",
        ],
        "Казахстан": ["Алматы", "Астана", "Шымкент", "Караганда"],
        "Беларусь": ["Минск", "Гомель", "Витебск", "Могилёв"],
        "Узбекистан": ["Ташкент", "Самарканд", "Бухара"],
        "Киргизия": ["Бишкек", "Ош"],
    ]

    static func cities(for country: String) -> [String] {
        citiesByCountry[country] ?? []
    }
}
